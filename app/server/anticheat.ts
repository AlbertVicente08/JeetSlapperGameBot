// Bot detector and game verification.
// - quickCheck: cheap, runs on EVERY game (only looks at the tap log).
// - replayCheck: replays the whole game from the seed; used when a game would enter a top 3.
import { HOLES, MAX_BONUS_MS, replay, ROUND_MS, type Tap } from '../src/game/engine.ts'

export type Status = 'ok' | 'suspicious' | 'rejected'

export interface Verdict {
  status: Status
  reason?: string
  stats: Record<string, number>
}

const MAX_GAME_MS = ROUND_MS + MAX_BONUS_MS
const MAX_TAPS = 800

// Thresholds (tune them by looking at the games table)
const MAX_TAPS_PER_SEC = 10 // a very fast human sustains 6-8 taps/s
const MIN_INTERVAL_CV = 0.15 // too regular a rhythm = machine
const MIN_MEDIAN_REACTION_MS = 170 // typical human reaction 200-350 ms
const MAX_FAST_REACTION_SHARE = 0.3 // share of reactions under 120 ms
const FAST_REACTION_MS = 120
const PERFECT_GAME_MIN_TAPS = 60

/** Validates the shape of the tap log. */
export function validateTaps(taps: unknown): taps is Tap[] {
  if (!Array.isArray(taps) || taps.length > MAX_TAPS) return false
  let last = -1
  for (const t of taps) {
    if (!Array.isArray(t) || t.length !== 3) return false
    const [ms, hole, trusted] = t
    if (!Number.isInteger(ms) || ms < 0 || ms > MAX_GAME_MS || ms < last) return false
    if (!Number.isInteger(hole) || hole < 0 || hole >= HOLES) return false
    if (trusted !== 0 && trusted !== 1) return false
    last = ms
  }
  return true
}

const median = (xs: number[]) => {
  if (!xs.length) return 0
  const s = [...xs].sort((a, b) => a - b)
  const m = s.length >> 1
  return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2
}

/** Quick review of the tap log (without replaying the game). */
export function quickCheck(taps: Tap[], score: number, realElapsedMs: number): Verdict {
  const n = taps.length
  const lastTap = n ? taps[n - 1][0] : 0
  const untrusted = taps.filter(t => t[2] === 0).length
  const intervals: number[] = []
  for (let i = 1; i < n; i++) intervals.push(taps[i][0] - taps[i - 1][0])
  const mean = intervals.length ? intervals.reduce((a, b) => a + b, 0) / intervals.length : 0
  const sd = intervals.length ? Math.sqrt(intervals.reduce((a, b) => a + (b - mean) ** 2, 0) / intervals.length) : 0
  const cv = mean ? sd / mean : 0
  const tapsPerSec = n / Math.max(1, Math.min(lastTap, MAX_GAME_MS) / 1000)

  const stats = {
    taps: n,
    untrusted,
    tapsPerSec: Math.round(tapsPerSec * 100) / 100,
    intervalCv: Math.round(cv * 1000) / 1000,
    realElapsedMs,
  }
  const verdict = (status: Status, reason?: string): Verdict => ({ status, reason, stats })

  if (score > 0 && n === 0) return verdict('rejected', 'Points without a single tap')
  if (realElapsedMs < ROUND_MS - 2_000) return verdict('rejected', 'The game lasted less than possible')
  if (lastTap > realElapsedMs + 2_000) return verdict('rejected', 'Taps outside the real game time')
  if (untrusted > 0) return verdict('rejected', 'Taps generated by code, not by a finger')
  if (tapsPerSec > MAX_TAPS_PER_SEC) return verdict('rejected', 'Too many taps per second')
  // With PUMP + FINAL PUMP + x3 combo a tap is worth at most 50 x 12 = 600
  if (score > n * 600) return verdict('rejected', 'Impossible score for those taps')
  if (n >= 30 && cv < MIN_INTERVAL_CV) return verdict('suspicious', 'Tap rhythm too regular')
  return verdict('ok')
}

/** Replays the game from the seed and analyses reaction times. */
export function replayCheck(seed: number, taps: Tap[], score: number): Verdict {
  const { state, hits, misses } = replay(seed, taps)
  const reactions = hits.map(h => h.reaction)
  const badHits = hits.filter(h => h.kind === 'holder' || h.kind === 'rug').length
  const fast = reactions.filter(r => r < FAST_REACTION_MS).length
  const stats = {
    replayScore: state.score,
    medianReactionMs: Math.round(median(reactions)),
    fastReactionShare: reactions.length ? Math.round((fast / reactions.length) * 100) / 100 : 0,
    badHits,
    misses,
  }
  const verdict = (status: Status, reason?: string): Verdict => ({ status, reason, stats })

  if (state.score !== score) return verdict('rejected', "The game doesn't add up when replayed")
  if (reactions.length >= 10 && stats.medianReactionMs < MIN_MEDIAN_REACTION_MS)
    return verdict('rejected', 'Reactions faster than a human')
  if (reactions.length >= 10 && stats.fastReactionShare > MAX_FAST_REACTION_SHARE)
    return verdict('rejected', 'Too many instant reactions')
  if (taps.length >= PERFECT_GAME_MIN_TAPS && badHits === 0 && misses === 0)
    return verdict('suspicious', 'Perfect game: pending manual review')
  return verdict('ok')
}
